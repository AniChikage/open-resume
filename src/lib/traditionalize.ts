export function toTraditional(value: string) {
  return String(value).replace(/[\u3400-\u9fff]/g, (character) => TRADITIONAL_CHARACTER_MAP[character] || character);
}

export function localizeTraditionalValue(value: unknown): unknown {
  if (typeof value === "string") return toTraditional(value);
  if (Array.isArray(value)) return value.map(localizeTraditionalValue);
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeTraditionalValue(item)]));
  return value;
}
