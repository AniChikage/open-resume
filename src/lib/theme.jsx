function interpolate(message, values) {
  return String(message).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? `{${key}}`);
}

export function readStoredLanguage() {
  if (typeof window === 'undefined') return 'en';
  try {
    const requested = new URLSearchParams(window.location.search).get('lang');
    if (SUPPORTED_LANGUAGES.some(({ code }) => code === requested)) return requested;
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return SUPPORTED_LANGUAGES.some(({ code }) => code === stored) ? stored : 'en';
  } catch {
    return 'en';
  }
}

export function translate(lang, message, values = {}) {
  let template = message;
  if (GEO_TRANSLATIONS[message]?.[lang]) template = GEO_TRANSLATIONS[message][lang];
  else if (GROWTH_TRANSLATIONS[message]?.[lang]) template = GROWTH_TRANSLATIONS[message][lang];
  else if (TAILORING_TRANSLATIONS[message]?.[lang]) template = TAILORING_TRANSLATIONS[message][lang];
  else if (LANDING_TRANSLATIONS[message]?.[lang]) template = LANDING_TRANSLATIONS[message][lang];
  else if (EDITOR_TRANSLATIONS[message]?.[lang]) template = EDITOR_TRANSLATIONS[message][lang];
  else if (lang === 'zh') template = ZH_TRANSLATIONS[message] ?? message;
  else if (lang === 'zh-TW') template = TRADITIONAL_OVERRIDES[message] ?? toTraditional(ZH_TRANSLATIONS[message] ?? message);
  else if (lang !== 'en') template = EXTRA_TRANSLATIONS[lang]?.[message] ?? message;
  return interpolate(template, values);
}

export function ThemeProvider({ children, initialLanguage }) {
  const [lang, setLangState] = useState(() => initialLanguage || readStoredLanguage());

  const setLang = useCallback((nextLanguage) => {
    const language = SUPPORTED_LANGUAGES.some(({ code }) => code === nextLanguage) ? nextLanguage : 'en';
    // Keep an explicit landing-page language consistent with later user choices.
    const url = new URL(window.location.href);
    if (url.searchParams.has('lang')) {
      url.searchParams.set('lang', language);
      window.history.replaceState(window.history.state, '', url);
    }
    setLangState(language);
  }, []);

  useEffect(() => {
    document.documentElement.classList.remove('dark');
    document.documentElement.lang = SUPPORTED_LANGUAGES.find(({ code }) => code === lang)?.htmlLang || 'en';
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch {
      // Language still works for this session when storage is unavailable.
    }
  }, [lang]);

  const t = useCallback((message, values) => translate(lang, message, values), [lang]);
  const value = useMemo(() => ({
    theme: 'light',
    lang,
    setLang,
    t,
    toggleTheme: () => {},
    toggleLang: () => setLang(lang === 'en' ? 'zh' : 'en'),
  }), [lang, setLang, t]);

  return (
    <ThemeContext.Provider value={value}>{children}</ThemeContext.Provider>
  );
}

export function useTheme() {
  return useContext(ThemeContext);
}
