"""Rebuild small PDF fonts: uv run --with fonttools python scripts/subset-pdf-fonts.py.

Derived from bundled SIL OFL Noto CJK, preserving glyph outlines and metrics.
Full CJK fonts remain available for documents using other characters.
"""
from pathlib import Path
import json
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1] / 'public' / 'fonts'
# Deliberately bounded coverage; pdf-fonts checks every character before using it.
ranges = [(0x20, 0x024F), (0x0300, 0x052F), (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F), (0x2190, 0x21FF), (0x2500, 0x25FF), (0xFFFD, 0xFFFD)]
latin = {cp for start, end in ranges for cp in range(start, end + 1)}
common = latin | {9, 10, 13}
# Python's standard codec is a reproducible character inventory, not a guessed
# list of common names. Characters outside this inventory use the full fonts.
for high in range(0xA1, 0xF8):
    for low in range(0xA1, 0xFF):
        try: common.add(ord(bytes([high, low]).decode('gb2312')))
        except UnicodeDecodeError: pass
coverage = set(common)
for family in ['Sans', 'Serif']:
    for weight in ['Regular', 'Bold']:
        for group, characters in [('Latin', latin), ('Common', common)]:
            font = TTFont(root / f'Noto{family}CJKsc-{weight}.otf')
            if group == 'Common': coverage &= set(font.getBestCmap()) | {9, 10, 13}
            options = subset.Options()
            options.name_IDs = ['*']
            options.notdef_outline = True
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=characters)
            sub.subset(font)
            names = {1: f'Resume {family} {group}', 3: f'Resume{family}{group}-{weight}', 4: f'Resume {family} {group} {weight}', 6: f'Resume{family}{group}-{weight}', 16: f'Resume {family} {group}'}
            for record in font['name'].names:
                if record.nameID in names: record.string = names[record.nameID].encode(record.getEncoding(), errors='replace')
            if 'CFF ' in font:
                cff = font['CFF '].cff
                cff.fontNames = [names[6]]
                cff.topDictIndex[0].FamilyName = names[1]
                cff.topDictIndex[0].FullName = names[4]
            target = root / f'Resume{family}{group}-{weight}.otf'
            font.save(target)
            print(f'{family} {group} {weight}: {target.stat().st_size} bytes')
project = root.parents[1]
target = project / 'src' / 'lib' / ('pdf-common-coverage.ts' if (project / 'src/main.tsx').exists() else 'pdf-common-coverage.js')
target.write_text('// Generated by scripts/subset-pdf-fonts.py; exact common-font coverage.\nexport const PDF_COMMON_CHARACTERS = ' + json.dumps(''.join(map(chr, sorted(coverage))), ensure_ascii=False) + ';\n')
